internal static class ListExtensions
{
    public static int FindLastIndex<T>(this IReadOnlyList<T> items, Func<T, bool> predicate)
    {
        for (var index = items.Count - 1; index >= 0; index--)
        {
            if (predicate(items[index]))
            {
                return index;
            }
        }

        return -1;
    }
